"""Route options from OSRM.

OSRM's ``alternatives`` frequently returns fewer than three routes for long
trips, so missing options are generated by forcing the route through via
points offset to either side of the trip's midpoint. Candidates are kept only
if they are meaningfully different from the routes we already have and not
absurdly slower than the fastest one.
"""

from __future__ import annotations

import logging
from concurrent.futures import FIRST_COMPLETED, ThreadPoolExecutor, wait
from dataclasses import dataclass

import numpy as np
from django.conf import settings
from django.core.cache import cache

from . import geo
from .http import ExternalServiceError, session

log = logging.getLogger(__name__)

TARGET_ROUTES = 3
MAX_SLOWDOWN = 1.6  # a generated alternative may be at most 60% slower
MAX_OVERLAP = 0.80  # ...and share at most 80% of its length with another route
OVERLAP_RADIUS_MI = 0.6
VIA_OFFSETS = (0.12, -0.12, 0.25, -0.25)  # fraction of straight-line distance
HEDGE_AFTER_S = 5.0


@dataclass
class RawRoute:
    coords: np.ndarray  # (N, 2) lat/lon, full resolution
    seg_seconds: np.ndarray  # (N-1,) OSRM travel time per segment
    distance_mi: float
    duration_s: float
    source: str  # "osrm" or "via"


class _NoRoute(Exception):
    pass


def _get(base: str, path: str, params: dict, timeout: float) -> dict:
    resp = session().get(f"{base.rstrip('/')}/{path}", params=params, timeout=timeout)
    data = resp.json()
    if data.get("code") == "Ok":
        return data
    if data.get("code") in {"NoRoute", "NoSegment"}:
        raise _NoRoute()
    raise RuntimeError(data.get("message") or data.get("code"))


def _request(path: str, params: dict, timeout: float = 60) -> dict:
    """GET from the first OSRM server, hedging to the next if it is slow or fails.

    Public OSRM servers vary from <1 s to >15 s for the same query. If the
    current server hasn't answered after ``HEDGE_AFTER_S`` (or errors), the
    same request goes to the next server and the first good answer wins.
    """
    bases = list(settings.OSRM_URLS)
    pool = ThreadPoolExecutor(max_workers=len(bases))
    pending: dict = {}
    last_error: Exception | None = None

    def launch():
        base = bases.pop(0)
        pending[pool.submit(_get, base, path, params, timeout)] = base

    launch()
    try:
        while pending:
            done, _ = wait(
                list(pending), timeout=HEDGE_AFTER_S if bases else None, return_when=FIRST_COMPLETED
            )
            if not done:
                launch()  # slow: hedge
                continue
            for future in done:
                base = pending.pop(future)
                try:
                    return future.result()
                except _NoRoute:
                    raise ExternalServiceError(
                        "No drivable route was found between these locations."
                    ) from None
                except Exception as exc:  # network error, timeout, bad JSON, server error
                    last_error = exc
                    log.warning("OSRM %s failed: %s", base, exc)
                    if bases:
                        launch()
    finally:
        pool.shutdown(wait=False, cancel_futures=True)
    raise ExternalServiceError(f"Routing service unavailable ({last_error}).")


def _coord_path(points: list[tuple[float, float]]) -> str:
    return "route/v1/driving/" + ";".join(f"{lon:.6f},{lat:.6f}" for lat, lon in points)


def _parse_route(route: dict, source: str) -> RawRoute:
    coords = np.array(geo.decode_polyline(route["geometry"], precision=6))
    seg_seconds = np.concatenate(
        [np.asarray(leg["annotation"]["duration"], dtype=float) for leg in route["legs"]]
    )
    if len(seg_seconds) != len(coords) - 1:
        # Defensive: spread the total duration by segment length instead.
        lengths = geo.segment_lengths_mi(coords)
        total = lengths.sum() or 1.0
        seg_seconds = lengths / total * route["duration"]
    return RawRoute(
        coords=coords,
        seg_seconds=seg_seconds,
        distance_mi=route["distance"] / geo.METERS_PER_MILE,
        duration_s=float(route["duration"]),
        source=source,
    )


def _full_routes(points: list[tuple[float, float]], alternatives: bool) -> list[dict]:
    params = {
        "overview": "full",
        "geometries": "polyline6",
        "annotations": "duration",
        "steps": "false",
    }
    if alternatives:
        params["alternatives"] = str(TARGET_ROUTES)
    return _request(_coord_path(points), params)["routes"]


def _quick_route(points: list[tuple[float, float]]) -> dict | None:
    """Cheap simplified-geometry route used only to screen via candidates."""
    try:
        data = _request(
            _coord_path(points),
            {"overview": "simplified", "geometries": "polyline6", "steps": "false"},
            timeout=30,
        )
    except ExternalServiceError:
        return None
    return data["routes"][0]


def overlap_ratio(candidate: np.ndarray, other: np.ndarray) -> float:
    """Share of ``candidate``'s length that runs along ``other``."""
    a = geo.resample(candidate, 1.0)
    b = geo.resample(other, 0.5)
    return float(np.mean(geo.min_distance_mi(a, b) <= OVERLAP_RADIUS_MI))


def _is_distinct(coords: np.ndarray, existing: list[np.ndarray], max_overlap: float) -> bool:
    return all(overlap_ratio(coords, other) < max_overlap for other in existing)


def _via_points(origin, destination) -> list[tuple[float, float]]:
    (lat1, lon1), (lat2, lon2) = origin, destination
    straight = float(geo.haversine_mi(lat1, lon1, lat2, lon2))
    bearing = geo.initial_bearing(lat1, lon1, lat2, lon2)
    mid = geo.destination_point(lat1, lon1, bearing, straight / 2)
    return [
        geo.destination_point(mid[0], mid[1], bearing + (90 if f > 0 else -90), abs(f) * straight)
        for f in VIA_OFFSETS
    ]


def _screen_vias(origin, destination) -> list[tuple[float, tuple[float, float], np.ndarray]]:
    """Cheap simplified routes through each via candidate: (duration, via, shape)."""
    vias = _via_points(origin, destination)
    with ThreadPoolExecutor(max_workers=len(vias)) as pool:
        quick = list(pool.map(lambda via: _quick_route([origin, via, destination]), vias))
    screened = [
        (route["duration"], via, np.array(geo.decode_polyline(route["geometry"])))
        for via, route in zip(vias, quick)
        if route is not None
    ]
    return sorted(screened, key=lambda item: item[0])


def _pick_alternatives(origin, destination, existing: list[RawRoute], screened, needed: int) -> list[RawRoute]:
    fastest = min(r.duration_s for r in existing)
    candidates = [c for c in screened if c[0] <= fastest * MAX_SLOWDOWN]
    chosen: list[tuple[float, float]] = []
    kept_shapes = [r.coords for r in existing]
    # Prefer clearly different corridors; relax if that leaves us short.
    for max_overlap in (MAX_OVERLAP, 0.95):
        for _, via, shape in candidates:
            if len(chosen) >= needed or via in chosen:
                continue
            if _is_distinct(shape, kept_shapes, max_overlap):
                chosen.append(via)
                kept_shapes.append(shape)
        if len(chosen) >= needed:
            break

    def fetch(via):
        return _parse_route(_full_routes([origin, via, destination], alternatives=False)[0], "via")

    with ThreadPoolExecutor(max_workers=2) as pool:
        return list(pool.map(fetch, chosen))


def get_routes(origin: tuple[float, float], destination: tuple[float, float]) -> list[RawRoute]:
    """Up to three distinct route options, fastest first (cached)."""
    key = "routes:{:.4f},{:.4f}:{:.4f},{:.4f}".format(*origin, *destination)
    cached = cache.get(key)
    if cached is not None:
        return cached

    # Screen via-point candidates while the (slow) alternatives query runs.
    with ThreadPoolExecutor(max_workers=2) as pool:
        main = pool.submit(_full_routes, [origin, destination], True)
        screening = pool.submit(_screen_vias, origin, destination)

        routes: list[RawRoute] = []
        for raw in main.result():
            parsed = _parse_route(raw, "osrm")
            if _is_distinct(parsed.coords, [r.coords for r in routes], 0.98):
                routes.append(parsed)
            if len(routes) == TARGET_ROUTES:
                break

        if len(routes) < TARGET_ROUTES:
            try:
                routes += _pick_alternatives(
                    origin, destination, routes, screening.result(), TARGET_ROUTES - len(routes)
                )
            except ExternalServiceError as exc:
                log.warning("Could not generate extra alternatives: %s", exc)

    routes.sort(key=lambda r: r.duration_s)
    cache.set(key, routes, settings.ROUTE_CACHE_SECONDS)
    return routes
